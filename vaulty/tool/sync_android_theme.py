#!/usr/bin/env python3
"""Generate native launch colors from the single Dart palette source."""
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
text = (root / 'lib/core/theme/app_colors.dart').read_text()
colors = dict(re.findall(r'static const (\w+)\s*=\s*Color\(\s*0xFF([A-Fa-f0-9]{6})\s*,?\s*\)', text))
res = root / 'android/app/src/main/res'
for directory, bg, fg in [('values', 'background', 'primaryInk'), ('values-night', 'backgroundDark', 'primaryDark')]:
    (res / directory).mkdir(parents=True, exist_ok=True)
    (res / directory / 'colors.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/sync_android_theme.py. Edit core/theme/app_colors.dart. -->
<resources>
  <color name="vault_background">#{colors[bg]}</color>
  <color name="vault_primary">#{colors[fg]}</color>
</resources>
''')
    parent = 'Theme.AppCompat.DayNight.NoActionBar'
    (res / directory / 'styles.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
  <style name="LaunchTheme" parent="{parent}">
    <item name="android:windowBackground">@drawable/launch_background</item>
    <item name="android:statusBarColor">@color/vault_background</item>
    <item name="android:navigationBarColor">@color/vault_background</item>
  </style>
  <style name="NormalTheme" parent="{parent}">
    <item name="android:windowBackground">@color/vault_background</item>
    <item name="android:statusBarColor">@color/vault_background</item>
    <item name="android:navigationBarColor">@color/vault_background</item>
  </style>
</resources>
''')
for directory in ['drawable', 'drawable-v21']:
    (res / directory / 'launch_background.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
  <item android:drawable="@color/vault_background" />
</layer-list>
''')
(res / 'drawable/ic_vaulty.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
  <path android:fillColor="@color/vault_background" android:pathData="M0,0H108V108H0Z" />
  <path android:fillColor="@color/vault_primary" android:pathData="M27,33Q24,33 24,38V72Q24,77 29,77H79Q84,77 84,72V42Q84,37 79,37H52L47,33Z" />
  <path android:fillColor="@color/vault_background" android:pathData="M48,51Q48,43 54,43Q60,43 60,51V54H63V68H45V54H48ZM51,54H57V51Q57,47 54,47Q51,47 51,51Z" />
</vector>
''')
for icon in res.glob('mipmap-*/ic_launcher.png'):
    icon.unlink()
manifest = root / 'android/app/src/main/AndroidManifest.xml'
manifest.write_text(manifest.read_text().replace('@mipmap/ic_launcher', '@drawable/ic_vaulty'))
print('Native Android launch palette synchronized.')

# Keep the static browser boot screen on the same palette as Flutter.
web = root / 'web/index.html'
if web.exists():
    html = web.read_text()
    html = re.sub(r'(name="theme-color" content=")#[0-9A-Fa-f]{6}', lambda m: m[1] + '#' + colors['background'], html)
    html = re.sub(r'(html,body\{[^}]*background:)#[0-9A-Fa-f]{6}', lambda m: m[1] + '#' + colors['background'], html)
    web.write_text(html)
