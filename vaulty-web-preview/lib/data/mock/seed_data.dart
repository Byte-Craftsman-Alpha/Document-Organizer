List<ShareRecord> seedShares(List<Document> docs, DateTime now) =>
    List.generate(
      6,
      (i) => ShareRecord(
        id: 'share-$i',
        documentId: docs[i].id,
        documentTitle: docs[i].title,
        recipients: [i.isEven ? 'rohan@example.com' : 'advisor@example.com'],
        role: i == 4 ? ShareRole.edit : ShareRole.view,
        expiresAt: now.add(Duration(days: i == 3 ? -2 : 7 + i)),
        revoked: i == 5,
      ),
    );
List<AuditEvent> seedEvents(List<Document> docs, DateTime now) => List.generate(
  16,
  (i) => AuditEvent(
    id: 'event-$i',
    event: ['Uploaded', 'Viewed', 'Shared', 'Renewed'][i % 4],
    documentTitle: docs[i % docs.length].title,
    documentId: docs[i % docs.length].id,
    actor: i % 4 == 2 ? 'rohan@example.com' : 'You',
    at: now.subtract(Duration(hours: i * 5)),
  ),
);
